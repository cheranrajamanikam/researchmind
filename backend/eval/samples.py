def make_pdf(path: Path, pages: list[list[Any]], footer: str = SYNTHETIC_NOTE) -> None:
    """Write a text-layer PDF. Each inner list becomes one PDF page (paragraphs or a table dict)."""
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    styles = getSampleStyleSheet()
    story: list[Any] = []
    for pi, blocks in enumerate(pages):
        for b in blocks:
            if isinstance(b, dict):
                story.append(Paragraph(b["table"], styles["Heading4"]))
                t = Table(b["rows"], hAlign="LEFT")
                t.setStyle(TableStyle([
                    ("GRID", (0, 0), (-1, -1), 0.6, colors.black),
                    ("FONTSIZE", (0, 0), (-1, -1), 10),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                ]))
                story.append(t)
                story.append(Spacer(1, 10))
            else:
                story.append(Paragraph(str(b), styles["Title"] if b is blocks[0] and pi == 0 else styles["BodyText"]))
                story.append(Spacer(1, 8))
        if pi < len(pages) - 1:
            story.append(PageBreak())

    def foot(canvas, doc):  # noqa: ANN001
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.drawString(40, 20, footer)
        canvas.restoreState()

    SimpleDocTemplate(str(path), pagesize=A4, title="", author="").build(story, onFirstPage=foot, onLaterPages=foot)


def write_samples(directory: Path) -> list[tuple[dict[str, Any], Path]]:
    directory.mkdir(parents=True, exist_ok=True)
    out = []
    for spec in PAPERS:
        path = directory / f"{spec['slug']}.pdf"
        make_pdf(path, spec["pages"])
        out.append((spec, path))
    return out


